def fails(m):
    """返回该标的未通过的条件说法列表；空列表 = 四道全过。"""
    return [lab for k, ok, lab in FILTERS if not ok(m[k])]


def qualifies(m):
    """是否凭自身指标满足四道过滤（不含人工纳入）。"""
    return not fails(m)


