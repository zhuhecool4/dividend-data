# rebuild_div.py 写、export_ui_data.py 读，两边必须一致，所以放这里。
DIV_EX, DIV_PER, DIV_RP, DIV_REC, DIV_PLAN, DIV_NOTICE, DIV_PROG, DIV_EPS = range(8)

# 进度字段里算"已过会"的取值，喂 div_is_pending。
# ⚠️ 逐值列举，不要写成前缀匹配 `startswith('股东大会')` —— '股东大会否决' 同样
#    没有日期、公告日也晚于报告期，会被一起放进来（全量 1 行，中兴通讯 2017 年报），
#    等于把一笔已经被否掉的分红挂进日历。想加取值就往这个元组里加。
PENDING_PROG = ('董事会决议通过', '股东大会通过', '股东大会决议通过')

# div_is_scheduled 的时间下界（报告期形态的字符串，可直接比大小）。
# 防的是数据源里那批 1999–2003 的"实施分配但没有除权日"老记录：其中 600572 康恩贝
# 那行有登记日 2004-03-29，会被认成"待实施"。现在它漏不出来纯属侥幸（不在 CAL_CODES，
# 且 calendar_events 末尾还有 ±时间窗过滤），但那是两道别的防线在兜，
# 这里补上它自己的。取"前年 1 月 1 日"：给跨年实施的年报分红留足余量。
SCHED_MIN_RP = f'{date.today().year - 2}-01-01'


def div_is_paid(row):
    """已实施且真有除息日的行 —— 只有这些能进股息率计算。

    未实施行（预披露/董事会决议通过/股东大会通过）也带 REPORT_DATE，
    若不排除，同一报告期的分红会被"预案 + 实施"计两次。

    注意收 `per == 0.0`（纯送股行）：它在股息率上是 0，不影响任何指标，
    但保留它才能让 by_rp 的年份键集合与原实现完全一致。
    """
    return row[DIV_PROG] == '实施分配' and bool(row[DIV_EX]) and row[DIV_PER] is not None


def div_is_pending(row):
    """未实施但有实质进展的预案行（分红日历的"未来事件"）。

    ⚠️ PLAN_NOTICE_DATE 有脏值：未实施行常常沿用上一期的公告日，
    实测招商银行 2026 中报那行写着 2026-03-28（早于报告期结束）、
    建发股份写着 2024-12-18。用"预案日必须晚于报告期"把它们滤掉。
    """
    if div_is_paid(row) or not row[DIV_PLAN] or not row[DIV_RP]:
        return False
    # 日期已经公告了就不算"日期未定" —— 那行归 div_is_scheduled，
    # 否则同一笔分红会同时挂在"预案"和"登记日"两边，自相矛盾。
    if row[DIV_EX] or row[DIV_REC]:
        return False
    # 2026-09-18：原先这里写死的是 '股东大会通过'，而数据源的实际取值是
    # '股东大会决议通过'（多"决议"两个字），16 笔中报分红因此被静默丢掉 ——
    # 它们的预案日都在 2026-07-20 ~ 08-28，和"公告日晚于报告期"那道门槛无关，
    # 纯粹卡在字符串比较上。其中 4 只在老登池（000999 华润三九 / 603323 苏农银行 /
    # 600273 嘉化能源 / 601019 山东出版），它们的 2026 中报分红当时从日历里完全消失。
    return row[DIV_PROG] in PENDING_PROG and row[DIV_PLAN] > row[DIV_RP]

def div_is_scheduled(row):
    """日期已公告（登记日或除权日有值）、但状态还没走到"实施分配"的行。

    ⚠️ 这类行以前被两头丢掉：不算已实施（状态不符），又因为 PLAN_NOTICE_DATE
    是脏值（沿用上一期公告日）被 div_is_pending 的"公告日必须晚于报告期"挡掉，
    于是在 App 里彻底消失。2026-09-18 复核，窗口内 5 行：
        601390 中国中铁  登记 09-30 / 除权 10-08     ← 原本完全看不到
        601688 华泰证券  登记 10-22 / 除权 10-23     ← 原本完全看不到
        600028 中国石化  登记 09-29  601919 中远海控  登记 10-22  601658 邮储银行  登记 12-10
    日期本身可信（登记日都在除权日前一交易日），没道理跟着脏公告日一起丢。
    （这 5 行里只有 4 行进得了日历：601688 华泰证券在 poolRest，
      日历只遍历 CAL_CODES = QUAL + BROAD + SELFADD。）

    ⚠️ 必须有时间下界（见 SCHED_MIN_RP）：判据只看"日期有没有值"，
    数据源里 1999–2003 那批"实施分配但除权日缺失"的老记录只要带一个登记日
    就会被认成"待实施" —— 600572 康恩贝 就是这样，登记日 2004-03-29。

    注意：只用于【日历】。div_is_paid 不动 —— 它管的是股息率计算，
    放宽会让同一报告期的分红被"预案 + 实施"计两次。
    """
    if div_is_paid(row):
        return False
    if row[DIV_PROG] in ('取消分配', '股东大会否决'):
        return False
    if not (row[DIV_EX] or row[DIV_REC]):
        return False
    # 报告期缺失的行判不了新旧，一律不认（全量实测 0 行，所以这条不误伤）
    return bool(row[DIV_RP]) and row[DIV_RP] >= SCHED_MIN_RP


def div_is_undated(row):
    """已过会、金额是真的，但【预案公告日是脏值】的行 —— 单独成栏，不挂日期。

    这类行以前【三条路都不进】，直接从日历里消失（见「分红事件完整性复核.md」3.B）：
      · div_is_paid 不认（进度没到"实施分配"）
      · div_is_scheduled 不认（登记日/除权日都还没有）
      · div_is_pending 被"公告日必须晚于报告期"挡掉 —— 它们的 PLAN_NOTICE_DATE
        沿用了上一期公告日（2026-03~04），而报告期是 2026-06-30，董事会不可能在
        半年报截止前就通过中报分配方案，所以那一列确实是脏的。
    但【金额和进度都是真的】（进度已过会、每股 > 0），整条丢掉才是可惜。

    处理：不挂日期（挂了就是往"未来事件"里塞 3/4 月的过去日期），
    单独归到日历的「已过会 · 日期待公告」一栏，只显示 名称 / 报告期 / 每股。
    2026-09-18 复核：全量 18 行，其中 8 只在入榜池。
    """
    if div_is_paid(row) or div_is_scheduled(row) or div_is_pending(row):
        return False
    if row[DIV_PROG] not in PENDING_PROG:       # 取消分配 / 股东大会否决 / 预披露 都不算
        return False
    if not row[DIV_RP] or not row[DIV_PER]:     # 没报告期或没金额（预披露常是 0）就没什么可说的
        return False
    return True


